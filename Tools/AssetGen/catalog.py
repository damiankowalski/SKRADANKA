"""The texture catalog (docs/art/textures/catalog): every generated variant worth keeping, chosen or not, as its
provenance .json and a small 2x2 preview. The full maps are not kept in the repository: they come back from the
.json with `generate.py --from <json>` (same model revision, mflux version, prompt, seed and settings).

    python Tools/AssetGen/catalog.py add Tools/AssetGen/out/cobblestone/cobblestone_1000.json --note "..."
    python Tools/AssetGen/catalog.py index        # rewrite the catalog's README.md
    python Tools/AssetGen/catalog.py check        # exit 1 if a record is broken or README.md is stale

No model is needed; this runs anywhere (Tools/AssetGen/README.md)."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from assetgen import processing as proc  # noqa: E402

REPO = ROOT.parent.parent
CATALOG = REPO / "docs" / "art" / "textures" / "catalog"
ASSETS = REPO / "DemoProject" / "Assets"
PREVIEW_SIZE = 512


class CatalogError(Exception):
    pass


def add(record_path: Path, note: str, catalog: Path = CATALOG) -> Path:
    """Copy one variant into the catalog: its provenance (with the note) and its preview at PREVIEW_SIZE."""
    with open(record_path, encoding="utf-8") as file:
        record = json.load(file)
    problems = proc.validate_provenance(record)
    if problems:
        raise CatalogError(f"{record_path.name}: incomplete provenance: {', '.join(problems)}")
    preview = record_path.parent / record["files"]["preview"]
    if not preview.is_file():
        raise CatalogError(f"{record_path.name}: no preview {preview.name} beside it")
    if not note.strip():
        raise CatalogError(f"{record_path.name}: say what the variant looks like or could serve (--note)")
    folder = catalog / record["material"]
    folder.mkdir(parents=True, exist_ok=True)
    name = record_path.stem
    record["catalog"] = {"note": note.strip(), "preview": f"{name}.png"}
    Image.open(preview).convert("RGB").resize((PREVIEW_SIZE, PREVIEW_SIZE), Image.LANCZOS).save(
        folder / f"{name}.png", optimize=True)
    with open(folder / f"{name}.json", "w", encoding="utf-8") as file:
        json.dump(record, file, indent=2)
        file.write("\n")
    return folder / f"{name}.json"


def entries(catalog: Path = CATALOG) -> list[tuple[Path, dict]]:
    found = []
    for path in sorted(catalog.glob("*/*.json")):
        with open(path, encoding="utf-8") as file:
            found.append((path, json.load(file)))
    return found


def used_in(name: str, assets: Path = ASSETS) -> list[str]:
    """Where the game uses the variant: its albedo under DemoProject/Assets, by file name."""
    return sorted(str(path.parent.relative_to(assets)) for path in assets.rglob(f"{name}_albedo.png"))


def render_index(catalog: Path = CATALOG, assets: Path = ASSETS) -> str:
    lines = [
        "# Texture catalog",
        "",
        "Every generated variant worth keeping, chosen or not: its provenance `.json` (prompt, seed, model revision,",
        "settings, seam test) and a 2x2 preview at 512 px. The full maps (albedo, normal, metallic/roughness) are",
        "not stored here; they come back from the `.json` on the Mac (about 4 minutes, Tools/AssetGen/README.md):",
        "",
        "```sh",
        "Tools/AssetGen/.venv/bin/python Tools/AssetGen/generate.py --from docs/art/textures/catalog/<material>/<name>.json",
        "```",
        "",
        "Generated by `Tools/AssetGen/catalog.py index`; do not edit by hand. Add a variant with",
        "`catalog.py add <out>/<material>/<name>.json --note \"...\"`.",
    ]
    material = None
    for path, record in entries(catalog):
        if record["material"] != material:
            material = record["material"]
            lines += ["", f"## {material}", "", "| preview | variant | note | in the game |", "|---|---|---|---|"]
        name = path.stem
        places = used_in(name, assets)
        where = ", ".join(f"`{place}`" for place in places) if places else "no"
        note = record.get("catalog", {}).get("note", "").replace("|", "\\|")
        lines.append(f"| ![]({material}/{name}.png) | `{name}` (seed {record['seed']}, {record['size']} px, "
                     f"{record['quantize'] or 'full'}-bit) | {note} | {where} |")
    return "\n".join(lines) + "\n"


def check(catalog: Path = CATALOG, assets: Path = ASSETS) -> list[str]:
    problems = []
    for path, record in entries(catalog):
        for problem in proc.validate_provenance(record):
            problems.append(f"{path.name}: {problem}")
        if not record.get("catalog", {}).get("note"):
            problems.append(f"{path.name}: no catalog note")
        if not (path.parent / f"{path.stem}.png").is_file():
            problems.append(f"{path.name}: no preview {path.stem}.png")
    readme = catalog / "README.md"
    if not readme.is_file() or readme.read_text(encoding="utf-8") != render_index(catalog, assets):
        problems.append("README.md is stale: run Tools/AssetGen/catalog.py index")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="The texture catalog in docs/art/textures/catalog.")
    commands = parser.add_subparsers(dest="command", required=True)
    adding = commands.add_parser("add", help="copy variants (provenance .json + preview) into the catalog")
    adding.add_argument("records", nargs="+", type=Path)
    adding.add_argument("--note", required=True, help="what it looks like, what it could serve (one for all given)")
    commands.add_parser("index", help="rewrite the catalog's README.md")
    commands.add_parser("check", help="exit 1 if a record is broken or README.md is stale")
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)

    if args.command == "add":
        try:
            for record in args.records:
                print(f"Added {add(record, args.note).relative_to(REPO)}")
        except (OSError, json.JSONDecodeError, CatalogError) as error:
            print(f"Cannot add: {error}", file=sys.stderr)
            return 2
        args.command = "index"
    if args.command == "index":
        CATALOG.mkdir(parents=True, exist_ok=True)
        (CATALOG / "README.md").write_text(render_index(), encoding="utf-8")
        print(f"Wrote {(CATALOG / 'README.md').relative_to(REPO)}")
        return 0
    problems = check()
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
