#!/usr/bin/env python3
"""Builds props from their family scripts into DemoProject/Assets/Models/Props (Tools/PropGen/README.md).

    python3 Tools/PropGen/generate.py                 # every family, every variant
    python3 Tools/PropGen/generate.py crate barrel     # some families
    python3 Tools/PropGen/generate.py --check          # only check what is there (exit 1 on a problem)

Per variant: <family>_<variant>.glb (LOD0), _lod1.glb, _lod2.glb and <family>_<variant>.json (the provenance: the
script, its parameters, triangles per LOD, bounds, collision boxes, materials). Python's standard library only: no
Blender, no packages. The output is deterministic, so a regeneration that changes nothing changes no file.
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from families import FAMILIES  # noqa: E402
from propgen import check, glb  # noqa: E402
from propgen.mesh import Prop  # noqa: E402

REPO = HERE.parent.parent


def config():
    with open(HERE / "config.json", encoding="utf-8") as f:
        return json.load(f)


def source_hash(*paths):
    digest = hashlib.sha256()
    for path in paths:
        digest.update(Path(path).read_bytes().replace(b"\r\n", b"\n"))
    return digest.hexdigest()[:16]


def seed_of(family, variant):
    return int(hashlib.sha256(f"{family}/{variant}".encode()).hexdigest()[:8], 16)


def build(module, variant, settings):
    parameters = module.VARIANTS[variant]
    prop = Prop(settings["materials"], seed_of(module.FAMILY, variant))
    module.build(prop, **parameters)
    return prop, parameters


def generate(names, settings, assets, out_root):
    written = []
    for name in names:
        module = FAMILIES[name]
        folder = out_root / module.FAMILY
        folder.mkdir(parents=True, exist_ok=True)
        for variant in module.VARIANTS:
            prop, parameters = build(module, variant, settings)
            stem = f"{module.FAMILY}_{variant}"
            files = {}
            for lod in range(len(settings["lods"])):
                path = folder / (f"{stem}.glb" if lod == 0 else f"{stem}_lod{lod}.glb")
                glb.write(path, stem, prop.primitives(lod), settings["materials"], assets)
                files[f"lod{lod}"] = path.name
            low, high = prop.bounds(0)
            used = sorted({part.material for part in prop.parts})
            provenance = {
                "tool": "Penumbra PropGen",
                "family": module.FAMILY,
                "variant": variant,
                "script": f"Tools/PropGen/families/{Path(module.__file__).name}",
                "parameters": parameters,
                "source_hash": source_hash(module.__file__, HERE / "propgen" / "mesh.py"),
                "budget": module.BUDGET,
                "triangles": [prop.triangles(lod) for lod in range(len(settings["lods"]))],
                "bounds": {"min": [round(v, 4) for v in low], "max": [round(v, 4) for v in high]},
                "collision": [{"center": [round(v, 4) for v in c], "half_extents": [round(v, 4) for v in e]}
                              for c, e in prop.default_collision()],
                "materials": {m: {k: settings["materials"][m][k] for k in ("albedo", "normal", "metallic_roughness")
                                  if k in settings["materials"][m]} for m in used},
                "files": files,
                "license": "the owner's (generated by the repository's scripts)",
                "ai_generated": False,
            }
            meta = folder / f"{stem}.json"
            meta.write_text(json.dumps(provenance, indent=2) + "\n", encoding="utf-8")
            written.append(meta)
            print(f"{stem}: {provenance['triangles']} triangles, "
                  f"{[round(high[i] - low[i], 2) for i in range(3)]} m")
    return written


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("families", nargs="*", help=f"some of: {', '.join(FAMILIES)} (default: all)")
    parser.add_argument("--check", action="store_true", help="check the props that are there, write nothing")
    args = parser.parse_args()
    settings = config()
    assets = REPO / "DemoProject" / "Assets"
    out_root = REPO / settings["output"]
    unknown = [name for name in args.families if name not in FAMILIES]
    if unknown:
        parser.error(f"unknown families: {', '.join(unknown)}")
    if not args.check:
        generate(args.families or list(FAMILIES), settings, assets, out_root)
    problems = check.check_folder(out_root, settings, assets)
    for problem in problems:
        print("PROBLEM", problem)
    print(f"{'ok' if not problems else str(len(problems)) + ' problem(s)'}: {out_root}")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
